#!/usr/bin/env python3
"""Generate the public CLI reference using only the built binary's help paths."""

import argparse
import difflib
import os
from pathlib import Path
import re
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/guide/reference/cli.md"


def help_output(runner, args):
    result = subprocess.run(
        [str(runner), *args],
        check=True,
        capture_output=True,
        encoding="utf-8",
        env={**os.environ, "NO_COLOR": "1", "TERM": "dumb", "COLUMNS": "80"},
    )
    return "\n".join(line.rstrip() for line in result.stdout.splitlines()).rstrip()


def subcommands(help_text):
    in_commands = False
    for line in help_text.splitlines():
        if line == "Commands:":
            in_commands = True
        elif in_commands:
            if line and not line.startswith(" "):
                break
            match = re.match(r"^  ([a-z][a-z0-9-]*)(?:\s|$)", line)
            if match:
                yield match[1]


def command_sections(runner, path=()):
    output = help_output(runner, [*path, "--help"])
    yield " ".join(("runner", *path)), output
    for command in subcommands(output):
        yield from command_sections(runner, (*path, command))


def render(runner):
    sections = [
        ("Command overview", help_output(runner, ["help"])),
        ("Agent guide", help_output(runner, ["help", "agents"])),
        *command_sections(runner),
    ]
    parts = [
        "# CLI reference",
        "Every public `runner` command and option below comes from the CLI shipped with this guide. For a walkthrough, see [Drive Runner from agents](../guides/drive-runner-from-agents.md).",
        "> [!NOTE]\n> Generated by `make guide-cli`. Do not edit this page by hand. CI checks it against the built binary on macOS and Windows. Internal hook commands are intentionally excluded.",
        "\n".join(f"- [{title}](#{title.lower().replace(' ', '-')})" for title, _ in sections),
    ]
    for title, output in sections:
        parts.extend([f"## {title}", f"```text\n{output}\n```"])
    return "\n\n".join(parts) + "\n"


def render_chinese(content):
    # Translate only the wrapper; command output is shared byte for byte.
    replacements = {
        "# CLI reference": "# CLI 参考",
        "Every public `runner` command and option below comes from the CLI shipped with this guide. For a walkthrough, see [Drive Runner from agents](../guides/drive-runner-from-agents.md).": "以下所有公开 `runner` 命令和选项均来自与本指南一同发布的 CLI。操作流程见[让智能体操作 Runner](../guides/drive-runner-from-agents.md)。",
        "> Generated by `make guide-cli`. Do not edit this page by hand. CI checks it against the built binary on macOS and Windows. Internal hook commands are intentionally excluded.": "> 由 `make guide-cli` 生成，请勿手动编辑。CI 在 macOS 和 Windows 上与构建的二进制核对。内部钩子命令有意不列出。命令帮助保留英文原文。",
        "- [Command overview](#command-overview)": "- [命令概览](#命令概览)",
        "- [Agent guide](#agent-guide)": "- [智能体指南](#智能体指南)",
        "## Command overview": "## 命令概览",
        "## Agent guide": "## 智能体指南",
    }
    parts = content.split("```")
    for index in range(0, len(parts), 2):
        parts[index] = "\n".join(replacements.get(line, line) for line in parts[index].split("\n"))
    return "```".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runner", type=Path, required=True, help="Built runner CLI binary")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true", help="Fail without writing if stale")
    args = parser.parse_args()
    content = render(args.runner.resolve())
    outputs = [(args.output, content)]
    if args.output == OUTPUT:
        outputs.append((ROOT / "docs/guide/zh-CN/reference/cli.md", render_chinese(content)))
    stale = False
    for path, expected in outputs:
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != expected:
                sys.stderr.writelines(difflib.unified_diff(
                    current.splitlines(keepends=True), expected.splitlines(keepends=True),
                    fromfile=str(path), tofile="generated CLI reference",
                ))
                stale = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as output:
                output.write(expected)
            print(f"Wrote {path}")
    if stale:
        print("CLI reference is stale. Run make guide-cli and commit the result.", file=sys.stderr)
        return 1
    if args.check:
        print("CLI references are up to date.")
        if args.output == OUTPUT:
            subprocess.run([sys.executable, str(ROOT / "script/check-guide-translations.py")], check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
