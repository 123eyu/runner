#!/usr/bin/env python3
"""Generate the public CLI reference using only the built binary's help paths."""

import argparse
import difflib
import os
from pathlib import Path
import re
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/guide/reference/cli.md"


def help_output(runner, args):
    result = subprocess.run(
        [str(runner), *args],
        check=True,
        capture_output=True,
        encoding="utf-8",
        env={**os.environ, "NO_COLOR": "1", "TERM": "dumb", "COLUMNS": "80"},
    )
    return "\n".join(line.rstrip() for line in result.stdout.splitlines()).rstrip()


def subcommands(help_text):
    in_commands = False
    for line in help_text.splitlines():
        if line == "Commands:":
            in_commands = True
        elif in_commands:
            if line and not line.startswith(" "):
                break
            match = re.match(r"^  ([a-z][a-z0-9-]*)(?:\s|$)", line)
            if match:
                yield match[1]


def command_sections(runner, path=()):
    output = help_output(runner, [*path, "--help"])
    yield " ".join(("runner", *path)), output
    for command in subcommands(output):
        yield from command_sections(runner, (*path, command))


def render(runner):
    sections = [
        ("Command overview", help_output(runner, ["help"])),
        ("Agent guide", help_output(runner, ["help", "agents"])),
        *command_sections(runner),
    ]
    parts = [
        "# CLI reference",
        "Every public `runner` command and option below comes from the CLI shipped with this guide. For a walkthrough, see [Drive Runner from agents](../guides/drive-runner-from-agents.md).",
        "> [!NOTE]\n> Generated by `make guide-cli`. Do not edit this page by hand. CI checks it against the built binary on macOS and Windows. Internal hook commands are intentionally excluded.",
        "\n".join(f"- [{title}](#{title.lower().replace(' ', '-')})" for title, _ in sections),
    ]
    for title, output in sections:
        parts.extend([f"## {title}", f"```text\n{output}\n```"])
    return "\n\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runner", type=Path, required=True, help="Built runner CLI binary")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true", help="Fail without writing if stale")
    args = parser.parse_args()
    content = render(args.runner.resolve())
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != content:
            sys.stderr.writelines(difflib.unified_diff(
                current.splitlines(keepends=True), content.splitlines(keepends=True),
                fromfile=str(args.output), tofile="generated CLI reference",
            ))
            print("CLI reference is stale. Run make guide-cli and commit the result.", file=sys.stderr)
            return 1
        print("CLI reference is up to date.")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with args.output.open("w", encoding="utf-8", newline="\n") as output:
            output.write(content)
        print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
